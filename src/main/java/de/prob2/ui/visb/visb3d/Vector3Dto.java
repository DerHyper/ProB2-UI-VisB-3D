package de.prob2.ui.visb.visb3d;

public class Vector3Dto {
    public Float x;
    public Float y;
    public Float z;

    public Vector3Dto() {
        this.x = null;
        this.y = null;
        this.z = null;
    }

    public Vector3Dto(float x, float y, float z) {
        this.x = x;
        this.y = y;
        this.z = z;
    }
}
